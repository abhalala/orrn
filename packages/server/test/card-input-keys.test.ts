/**
 * Delta round S4 (brief decision 5): the draft card names every input key in the person's language. The web cannot
 * walk `appRouter`, so it reads a generated list, `apps/web/src/features/buddy/draft-card.input-keys.ts`. This test
 * keeps that list honest: every top-level key of every allowed mutation (and of the two composite import drafts) must
 * be in it. Regenerate with `CARD_KEYS_WRITE=1 bun test test/card-input-keys.test.ts`; the web test
 * `draft-card.test.tsx` then fails until each new key has words in en, hi and gu.
 */
import { describe, expect, test } from "bun:test";

import { REQUEST_KEYS } from "../src/lib/buddy/draftView";
import { buddyRegistry } from "../src/lib/buddy/registry";

const FIXTURE = new URL("../../../apps/web/src/features/buddy/draft-card.input-keys.ts", import.meta.url);

function fixtureText(keys: string[]): string {
  return [
    "// Generated by packages/server/test/card-input-keys.test.ts (CARD_KEYS_WRITE=1). Do not edit by hand.",
    "// Every top-level input key of every mutation the buddy may draft, plus the composite import drafts' keys.",
    "export const CARD_INPUT_KEYS = [",
    ...keys.map((k) => `  ${JSON.stringify(k)},`),
    "] as const;",
    "",
  ].join("\n");
}

/** Keys the card may show that the registry does not list as fields. */
const EXTRA = [
  // A non-object input (an array, e.g. `die.validateImport`) shows as one field keyed `input` (`draftCard`).
  "input",
  // The composite import drafts store `{ candidateId, answers }` and `{ candidateId }` (`importDrafts.ts`).
  "candidateId",
  "answers",
];

async function registryKeys(): Promise<string[]> {
  const keys = new Set<string>(EXTRA);
  for (const entry of (await buddyRegistry()).values()) {
    if (entry.kind !== "mutation" || entry.decision.kind !== "allow") continue;
    for (const field of entry.fields) keys.add(field);
  }
  // The card never shows the request keys: Confirm sets them to the draft id.
  for (const k of REQUEST_KEYS) keys.delete(k);
  return [...keys].sort();
}

describe("the card's list of input keys", () => {
  test("holds every top-level key of every allowed mutation", async () => {
    const keys = await registryKeys();
    if (process.env.CARD_KEYS_WRITE === "1") {
      await Bun.write(FIXTURE, fixtureText(keys));
    }
    const { CARD_INPUT_KEYS } = (await import(FIXTURE.href)) as { CARD_INPUT_KEYS: readonly string[] };
    const listed = new Set<string>(CARD_INPUT_KEYS);
    expect(keys.filter((k) => !listed.has(k))).toEqual([]);
    expect(keys.length).toBeGreaterThan(200);
  });
});
