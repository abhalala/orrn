/**
 * Writes src/en-public.gen.ts: the English strings the public `/` page
 * renders (src/public-keys.ts), which ride in the web entry chunk while the
 * full dictionary loads lazily. Run after changing PUBLIC_KEYS or one of
 * those strings:  bun run --cwd packages/i18n gen:public
 * src/public.test.ts fails when the file is out of date.
 */
import { writeFileSync } from "node:fs";

import { en } from "../src/en";
import { PUBLIC_KEYS, pickMessages } from "../src/public-keys";

export const PUBLIC_PATH = new URL("../src/en-public.gen.ts", import.meta.url);

export function renderPublic(): string {
  const body = JSON.stringify(pickMessages(en, PUBLIC_KEYS), null, 2);
  return `// Generated by \`bun run --cwd packages/i18n gen:public\` from en.ts and public-keys.ts. Do not edit.
// The English the public \`/\` page renders; the rest of en.ts loads lazily (loader.ts).
export const enPublic = ${body} as const;
`;
}

if (import.meta.main) {
  writeFileSync(PUBLIC_PATH, renderPublic());
  console.log(`wrote ${PUBLIC_PATH.pathname}`);
}
